/* ==========================================================================
   Chocolatey command builder
   Data: data/chocolatey.json (regenerated by tools/update-chocolatey.mjs)
   ========================================================================== */

(() => {
    'use strict';

    const STORAGE_KEY = 'msdl-choco';
    const state = {
        data: null,
        selected: [],
        query: '',
        category: 'all',
    };

    const el = {};

    const escapeHtml = (value) =>
        String(value ?? '').replace(/[&<>"']/g, (character) => ({
            '&': '&amp;',
            '<': '&lt;',
            '>': '&gt;',
            '"': '&quot;',
            "'": '&#39;',
        })[character]);

    const debounce = (fn, wait) => {
        let timer;
        return (...args) => {
            clearTimeout(timer);
            timer = setTimeout(() => fn(...args), wait);
        };
    };

    /* --------------------------------------------------------------- data */

    async function loadData() {
        try {
            const response = await fetch('data/chocolatey.json', { cache: 'no-cache' });
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            const data = await response.json();
            if (!Array.isArray(data.packages) || data.packages.length === 0) {
                throw new Error('The package list is empty.');
            }

            state.data = data;
            const updated = new Intl.DateTimeFormat('en', {
                month: 'short',
                day: 'numeric',
                year: 'numeric',
            }).format(new Date(data.updated));

            el.installCommand.textContent = data.installCommand;
            if (el.catalogSize) {
                el.catalogSize.textContent = `${data.packages.length} packages · updated ${updated}`;
            }
            if (el.footerStamp) {
                el.footerStamp.textContent = `data/chocolatey.json · ${data.packages.length} packages · ${updated}`;
            }

            restoreSelection();
            renderCategories();
            renderGrid();
            renderCommand();
        } catch (error) {
            el.grid.innerHTML = `
                <div class="alert" role="alert">
                    <svg class="icon alert-icon" aria-hidden="true" focusable="false" viewBox="0 0 20 20">
                        <path d="M10 3.2 18 17H2L10 3.2Z" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/>
                        <path d="M10 7.6v3.8" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round"/>
                    </svg>
                    <div>
                        <p class="alert-title">The package list could not be loaded</p>
                        <p class="alert-body">${escapeHtml(error.message)}. Reload the page to try again.</p>
                    </div>
                </div>`;
        }
    }

    /* ---------------------------------------------------------- selection */

    function restoreSelection() {
        const fromHash = decodeURIComponent(window.location.hash.replace(/^#/, ''))
            .split(',')
            .map((id) => id.trim())
            .filter(Boolean);

        let stored = [];
        if (fromHash.length > 0) {
            stored = fromHash;
        } else {
            try {
                stored = JSON.parse(localStorage.getItem(STORAGE_KEY) ?? '[]');
            } catch {
                stored = [];
            }
        }

        const known = new Set(state.data.packages.map((entry) => entry.id));
        state.selected = [...new Set(stored.filter((id) => known.has(id)))];
    }

    function saveSelection() {
        try {
            localStorage.setItem(STORAGE_KEY, JSON.stringify(state.selected));
        } catch {
            /* private mode — the command still works */
        }

        const hash = state.selected.length > 0 ? `#${state.selected.join(',')}` : '';
        history.replaceState(null, '', `${window.location.pathname}${window.location.search}${hash}`);
    }

    function toggle(id) {
        state.selected = state.selected.includes(id)
            ? state.selected.filter((entry) => entry !== id)
            : [...state.selected, id];

        saveSelection();
        renderGrid();
        renderCommand();
    }

    /* ----------------------------------------------------------- rendering */

    const matches = (entry) => {
        if (state.category !== 'all' && entry.category !== state.category) return false;
        if (!state.query) return true;
        const needle = state.query.toLowerCase();
        return `${entry.name} ${entry.id} ${entry.summary}`.toLowerCase().includes(needle);
    };

    function renderCategories() {
        const counts = new Map();
        for (const entry of state.data.packages) {
            counts.set(entry.category, (counts.get(entry.category) ?? 0) + 1);
        }

        const chips = [{ id: 'all', label: 'All', count: state.data.packages.length }].concat(
            state.data.categories.map((category) => ({
                ...category,
                count: counts.get(category.id) ?? 0,
            })),
        );

        el.categories.innerHTML = chips
            .map(
                (chip) => `<button class="cat" type="button" data-category="${escapeHtml(chip.id)}"
                    aria-pressed="${state.category === chip.id}">${escapeHtml(chip.label)}
                    <span class="filter-count">${String(chip.count).padStart(2, '0')}</span></button>`,
            )
            .join('');
    }

    function renderGrid() {
        if (!state.data) return;

        const visible = state.data.packages.filter(matches);
        const categoryLabel = new Map(state.data.categories.map((category) => [category.id, category.label]));
        const selected = new Set(state.selected);

        el.grid.setAttribute('aria-busy', 'false');

        if (visible.length === 0) {
            el.grid.innerHTML = `
                <div class="empty">
                    <p class="empty-title">No packages match</p>
                    <p class="empty-note">Try a different word, or switch back to all categories.</p>
                </div>`;
            return;
        }

        el.grid.innerHTML = visible
            .map(
                (entry) => `
                <button class="pkg" type="button" data-id="${escapeHtml(entry.id)}"
                    aria-pressed="${selected.has(entry.id)}">
                    <span class="pkg-check" aria-hidden="true">
                        <svg viewBox="0 0 20 20" focusable="false"><path d="m4 10.6 3.9 3.9L16 6.4" fill="none"
                            stroke="currentColor" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/></svg>
                    </span>
                    <span class="pkg-body">
                        <span class="pkg-name">${escapeHtml(entry.name)}</span>
                        <span class="pkg-meta">
                            <span class="pkg-id">${escapeHtml(entry.id)}</span>
                            <span aria-hidden="true">·</span>
                            <span>${escapeHtml(categoryLabel.get(entry.category) ?? entry.category)}</span>
                        </span>
                        ${entry.summary ? `<span class="pkg-summary">${escapeHtml(entry.summary)}</span>` : ''}
                    </span>
                </button>`,
            )
            .join('');
    }

    function commandText() {
        if (state.selected.length === 0) return '';
        return `choco install -y ${state.selected.join(' ')}`;
    }

    function renderCommand() {
        const command = commandText();
        el.bar.hidden = command === '';
        el.count.textContent =
            state.selected.length === 0
                ? ''
                : `${String(state.selected.length).padStart(2, '0')} selected`;
        if (command) el.output.textContent = command;
    }

    /* --------------------------------------------------------------- copy */

    async function copyText(text) {
        try {
            await navigator.clipboard.writeText(text);
            return true;
        } catch {
            try {
                const helper = document.createElement('textarea');
                helper.value = text;
                helper.style.position = 'fixed';
                helper.style.opacity = '0';
                document.body.appendChild(helper);
                helper.select();
                const ok = document.execCommand('copy');
                helper.remove();
                return ok;
            } catch {
                return false;
            }
        }
    }

    async function handleCopy(button, text) {
        if (!text) return;
        const ok = await copyText(text);
        if (!ok) return;

        const label = button.dataset.originalLabel ?? button.textContent.trim();
        button.dataset.originalLabel = label;
        button.classList.add('is-copied');

        if (button.id === 'command-copy') {
            button.textContent = 'Copied';
        } else {
            button.innerHTML = '<svg class="icon" aria-hidden="true" focusable="false" viewBox="0 0 20 20"><path d="m4 10.6 3.9 3.9L16 6.4" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg>';
        }

        window.setTimeout(() => {
            button.classList.remove('is-copied');
            if (button.id === 'command-copy') button.textContent = button.dataset.originalLabel;
            else button.innerHTML = button.dataset.originalHtml ?? button.innerHTML;
        }, 1500);
    }

    /* ---------------------------------------------------------------- init */

    function cacheElements() {
        Object.assign(el, {
            installCommand: document.getElementById('install-command'),
            catalogSize: document.getElementById('catalog-size'),
            categories: document.getElementById('choco-cats'),
            grid: document.getElementById('choco-grid'),
            filter: document.getElementById('pkg-filter'),
            bar: document.getElementById('command-bar'),
            output: document.getElementById('command-output'),
            count: document.getElementById('pkg-count'),
            reset: document.getElementById('command-reset'),
            copyCommand: document.getElementById('command-copy'),
            themeToggle: document.getElementById('theme-toggle'),
            footerStamp: document.getElementById('footer-stamp'),
        });
    }

    function bindEvents() {
        el.grid.addEventListener('click', (event) => {
            const button = event.target.closest('[data-id]');
            if (button) toggle(button.dataset.id);
        });

        el.categories.addEventListener('click', (event) => {
            const button = event.target.closest('[data-category]');
            if (!button) return;
            state.category = button.dataset.category;
            el.categories.querySelectorAll('[data-category]').forEach((chip) => {
                chip.setAttribute('aria-pressed', String(chip === button));
            });
            renderGrid();
        });

        el.filter.addEventListener(
            'input',
            debounce(() => {
                state.query = el.filter.value;
                renderGrid();
            }, 90),
        );

        el.reset.addEventListener('click', () => {
            state.selected = [];
            saveSelection();
            renderGrid();
            renderCommand();
        });

        el.copyCommand.addEventListener('click', () => handleCopy(el.copyCommand, commandText()));

        document.querySelectorAll('[data-copy-target]').forEach((button) => {
            const target = document.getElementById(button.dataset.copyTarget);
            button.dataset.originalHtml = button.innerHTML;
            button.addEventListener('click', () => handleCopy(button, target?.textContent ?? ''));
        });

        // Keep the browser's back/forward buttons in sync with shared links.
        window.addEventListener('hashchange', () => {
            restoreSelection();
            renderGrid();
            renderCommand();
        });
    }

    function initTheme() {
        const toggle = el.themeToggle;
        if (!toggle) return;

        const root = document.documentElement;
        toggle.addEventListener('click', () => {
            const next = root.dataset.theme === 'dark' ? 'light' : 'dark';
            root.dataset.theme = next;
            try {
                localStorage.setItem('msdl-theme', next);
            } catch {
                /* ignore */
            }
        });
    }

    function init() {
        cacheElements();
        initTheme();
        bindEvents();
        el.grid.innerHTML = Array.from({ length: 8 }, () => '<div class="skeleton" style="height:74px"></div>').join('');
        loadData();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init, { once: true });
    } else {
        init();
    }
})();
